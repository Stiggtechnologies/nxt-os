#!/usr/bin/env node
/**
 * Builds the gap register from the two observed catalogues.
 *
 * Every observed capability is dispositioned exactly once:
 *   routed   - opens a native NXT screen
 *   linked   - handled by another NXT app
 *   external - cannot be closed without an outside authority, credential or published spec
 *   open     - ours to build (includes capabilities the owner brought back in scope
 *              on 2026-11-22 after they had been recorded as out of scope)
 *   chrome   - the source product's own UI, not a bookkeeping capability
 *
 * Usage:
 *   node scripts/gap-register.mjs            print the register
 *   node scripts/gap-register.mjs --write     rewrite docs/GAP_REGISTER.md
 *   node scripts/gap-register.mjs --check     fail when docs/GAP_REGISTER.md is stale
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const readJson = relative => JSON.parse(fs.readFileSync(path.join(root, relative), "utf8"));

const EXTERNAL_GATE = /(CRA|certif|OAuth|credential|authority|NETFILE|Revenu|external gate|vendor (file|format|programme|program)|published (form|specification)|credentialed)/i;
const text = value => String(value ?? "");
const list = value => (Array.isArray(value) ? value : []);

function quickbooks() {
  const map = readJson("public/apps/ledger/qb-navigation.json");
  const rows = [];
  const walk = (nodes, group) =>
    list(nodes).forEach(node => {
      const label = node.label || group;
      if (list(node.children).length) walk(node.children, label);
      else rows.push({ product: "QuickBooks", group: group || label, node });
    });
  list(map.groups).forEach(group => walk(group.children, group.label));
  return rows;
}

function taxSource() {
  const catalog = readJson("public/apps/tax/source-map.json");
  const rows = [];
  for (const source of list(catalog.sources)) {
    for (const group of list(source.groups)) {
      for (const entry of list(group.entries)) {
        rows.push({ product: source.label || source.id, group: group.label || source.label || source.id, node: entry });
      }
    }
  }
  return rows;
}

export function disposition(node) {
  if (node.kind === "chrome") return "chrome";
  if (node.native_route) return "routed";
  if (list(node.related).length) return "linked";
  // An explicit owner re-scope wins over wording that would otherwise look gated:
  // the capability is ours to build, with its dependency recorded in the next step.
  if (node.scope === "in_scope") return "open";
  if (EXTERNAL_GATE.test(text(node.next_step)) || EXTERNAL_GATE.test(text(node.native_scope))) return "external";
  return "open";
}

export function register() {
  const rows = [...quickbooks(), ...taxSource()].map(row => ({
    product: row.product,
    group: row.group,
    id: row.node.id,
    label: text(row.node.label),
    disposition: disposition(row.node),
    route: text(row.node.native_route),
    next_step: text(row.node.next_step),
    scope_reason: text(row.node.scope_reason)
  }));
  const products = [...new Set(rows.map(row => row.product))];
  const summary = products.map(product => {
    const of = rows.filter(row => row.product === product);
    const count = name => of.filter(row => row.disposition === name).length;
    const capabilities = of.length - count("chrome");
    return {
      product,
      observed: of.length,
      chrome: count("chrome"),
      capabilities,
      routed: count("routed"),
      linked: count("linked"),
      external: count("external"),
      open: count("open"),
      percent: capabilities ? Math.round((count("routed") / capabilities) * 100) : 0
    };
  });
  const total = summary.reduce(
    (acc, row) => {
      for (const key of ["capabilities", "routed", "linked", "external", "open", "chrome"]) acc[key] += row[key];
      return acc;
    },
    { capabilities: 0, routed: 0, linked: 0, external: 0, open: 0, chrome: 0 }
  );
  total.percent = total.capabilities ? Math.round((total.routed / total.capabilities) * 100) : 0;
  return { rows, summary, total };
}

export function markdown(data = register()) {
  const lines = [];
  lines.push("# Gap register", "");
  lines.push("Generated by `node scripts/gap-register.mjs --write`. Do not edit by hand.", "");
  lines.push("Every observed capability is dispositioned exactly once: **routed** (opens a native NXT screen), **linked** (handled by another NXT app), **external** (needs an authority, credential or published specification), **open** (ours to build). On 2026-11-22 the owner brought every capability previously recorded as out of scope back into scope; those rows are open, and their original reason is kept as the recorded rationale. Source-product chrome is not a capability and is counted separately.", "");
  lines.push("## Totals", "");
  lines.push("| | Count |");
  lines.push("| --- | ---: |");
  lines.push(`| Capabilities observed | ${data.total.capabilities} |`);
  lines.push(`| Routed | ${data.total.routed} |`);
  lines.push(`| Linked | ${data.total.linked} |`);
  lines.push(`| External | ${data.total.external} |`);
  lines.push(`| **Open** | **${data.total.open}** |`);
  lines.push(`| Routed coverage | ${data.total.percent}% |`);
  lines.push(`| Source chrome excluded | ${data.total.chrome} |`);
  lines.push("");
  lines.push("## By product", "");
  lines.push("| Product | Capabilities | Routed | Linked | External | Open | Coverage |");
  lines.push("| --- | ---: | ---: | ---: | ---: | ---: | ---: |");
  for (const row of data.summary) {
    lines.push(`| ${row.product} | ${row.capabilities} | ${row.routed} | ${row.linked} | ${row.external} | ${row.open} | ${row.percent}% |`);
  }
  lines.push("");
  for (const row of data.summary) {
    const open = data.rows.filter(item => item.product === row.product && item.disposition === "open");
    const external = data.rows.filter(item => item.product === row.product && item.disposition === "external");
    lines.push(`## ${row.product}`, "");
    if (open.length) {
      lines.push(`### Open to build (${open.length})`, "");
      lines.push("| Group | Gap | Next step | Recorded rationale |");
      lines.push("| --- | --- | --- | --- |");
      for (const item of open) lines.push(`| ${item.group} | ${item.label} | ${item.next_step || "_no next step recorded_"} | ${item.scope_reason || ""} |`);
      lines.push("");
    }
    if (external.length) {
      lines.push(`### Blocked outside this codebase (${external.length})`, "");
      lines.push("| Group | Gap | Why |");
      lines.push("| --- | --- | --- |");
      for (const item of external) lines.push(`| ${item.group} | ${item.label} | ${item.next_step} |`);
      lines.push("");
    }
  }
  return lines.join("\n");
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const args = process.argv.slice(2);
  const data = register();
  const doc = path.join(root, "docs/GAP_REGISTER.md");
  if (args.includes("--write")) {
    fs.writeFileSync(doc, markdown(data) + "\n");
    console.log("wrote docs/GAP_REGISTER.md");
  } else if (args.includes("--baseline")) {
    const baseline = {
      note: "Pinned by scripts/gap-register.mjs --baseline. Raising open counts or lowering routed counts needs a deliberate regeneration.",
      generated_from: ["public/apps/ledger/qb-navigation.json", "public/apps/tax/source-map.json"],
      total: data.total,
      products: data.summary.map(row => ({ product: row.product, capabilities: row.capabilities, routed: row.routed, linked: row.linked, external: row.external, open: row.open })),
      open_ids: data.rows.filter(row => row.disposition === "open").map(row => row.id).sort(),
      external_ids: data.rows.filter(row => row.disposition === "external").map(row => row.id).sort()
    };
    fs.writeFileSync(path.join(root, "docs/progress-baseline.json"), JSON.stringify(baseline, null, 2) + "\n");
    console.log("wrote docs/progress-baseline.json");
  } else if (args.includes("--check")) {
    const current = fs.existsSync(doc) ? fs.readFileSync(doc, "utf8").replace(/\r\n/g, "\n") : "";
    const expected = markdown(data).replace(/\r\n/g, "\n") + "\n";
    if (current !== expected) {
      console.error("docs/GAP_REGISTER.md is stale. Run: node scripts/gap-register.mjs --write");
      process.exit(1);
    }
    console.log("gap register is current");
  } else {
    console.log(markdown(data));
  }
}
