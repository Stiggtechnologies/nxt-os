//! Draft ASPE-style statements, leadsheets and the uncorrected-misstatement
//! summary built from the existing engagement analysis. Pure, no I/O.
//! Output is a working draft for CPA review; it is not a claim of compliance
//! with ASPE or any CPA Canada standard.
use super::{analysis, models::*};
use serde_json::{Value, json};
use std::collections::BTreeMap;

pub const FORMAT: &str = "nxt-engagement-statements/v1";
pub const REVIEW_NOTICE: &str = "DRAFT - generated by NXT OS for CPA review. Presentation, classification and note wording must be reviewed and approved by a CPA before use. Not represented as compliant with ASPE (CPA Canada Handbook Part II) or any assurance or related-services standard.";

/// Statement line a group rolls into. GIFI ranges (CRA RC4088) are used when
/// present; otherwise the group kind decides.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Line {
    Cash,
    CurrentAsset,
    LongTermAsset,
    CurrentLiability,
    LongTermLiability,
    ShareCapital,
    RetainedEarnings,
    Dividends,
    OtherEquity,
    Revenue,
    CostOfSales,
    OperatingExpense,
    IncomeTax,
}
impl Line {
    pub fn label(self) -> &'static str {
        match self {
            Line::Cash => "Cash",
            Line::CurrentAsset => "Other current assets",
            Line::LongTermAsset => "Long-term assets",
            Line::CurrentLiability => "Current liabilities",
            Line::LongTermLiability => "Long-term liabilities",
            Line::ShareCapital => "Share capital",
            Line::RetainedEarnings => "Retained earnings, opening",
            Line::Dividends => "Dividends",
            Line::OtherEquity => "Other equity",
            Line::Revenue => "Revenue",
            Line::CostOfSales => "Cost of sales",
            Line::OperatingExpense => "Operating expenses",
            Line::IncomeTax => "Income taxes",
        }
    }
    fn key(self) -> &'static str {
        match self {
            Line::Cash => "cash",
            Line::CurrentAsset => "current_asset",
            Line::LongTermAsset => "long_term_asset",
            Line::CurrentLiability => "current_liability",
            Line::LongTermLiability => "long_term_liability",
            Line::ShareCapital => "share_capital",
            Line::RetainedEarnings => "retained_earnings_opening",
            Line::Dividends => "dividends",
            Line::OtherEquity => "other_equity",
            Line::Revenue => "revenue",
            Line::CostOfSales => "cost_of_sales",
            Line::OperatingExpense => "operating_expense",
            Line::IncomeTax => "income_tax",
        }
    }
}

pub fn classify(group: &Group) -> Line {
    let gifi = group.gifi_code.as_deref().and_then(|c| c.parse::<u32>().ok());
    match (group.kind.as_str(), gifi) {
        ("asset", Some(1000..=1007)) => Line::Cash,
        ("asset", Some(1008..=1599)) => Line::CurrentAsset,
        ("asset", Some(_)) => Line::LongTermAsset,
        ("asset", None) => Line::CurrentAsset,
        ("liability", Some(3140..=3499)) => Line::LongTermLiability,
        ("liability", _) => Line::CurrentLiability,
        ("equity", Some(3500..=3549)) => Line::ShareCapital,
        ("equity", Some(3700..=3740)) => Line::Dividends,
        ("equity", Some(3600..=3849)) => Line::RetainedEarnings,
        ("equity", _) => Line::OtherEquity,
        ("revenue", _) => Line::Revenue,
        ("expense", Some(8300..=8519)) => Line::CostOfSales,
        ("expense", Some(9990 | 9995)) => Line::IncomeTax,
        _ => Line::OperatingExpense,
    }
}

fn natural(kind: &str, debit_net: i64) -> i64 {
    if kind == "asset" || kind == "expense" { debit_net } else { -debit_net }
}
fn n(v: &Value, k: &str) -> i64 {
    v[k].as_i64().unwrap_or(0)
}

#[derive(Default, Clone, Copy)]
struct Amt {
    cur: i64,
    pri: i64,
}

/// Leadsheets, proposed-entry summary and draft statements for one engagement.
pub fn generate(input: &EngagementInput) -> Value {
    let analysis = analysis::analyze(input);
    if analysis["totals"].is_null() {
        return json!({"format":FORMAT,"review_notice":REVIEW_NOTICE,"supported":false,"diagnostics":analysis["diagnostics"].clone()});
    }
    let groups: BTreeMap<&str, &Group> = input.groups.iter().map(|g| (g.id.as_str(), g)).collect();
    let mut lines: BTreeMap<Line, Amt> = BTreeMap::new();
    let mut leadsheets = Vec::new();
    let mut by_group: BTreeMap<&str, Vec<&Value>> = BTreeMap::new();
    let rows = analysis["accounts"].as_array().cloned().unwrap_or_default();
    for row in &rows {
        if let Some(g) = row["group_id"].as_str() {
            by_group.entry(g).or_default().push(row);
        }
    }
    for group in &input.groups {
        let line = classify(group);
        let mut total = [0i64; 4];
        let mut accts = Vec::new();
        for row in by_group.get(group.id.as_str()).cloned().unwrap_or_default() {
            let kind = row["kind"].as_str().unwrap_or("asset");
            let base = natural(kind, n(row, "base_debit_cents") - n(row, "base_credit_cents"));
            let adj = natural(kind, n(row, "adjustment_debit_cents") - n(row, "adjustment_credit_cents"));
            let fin = natural(kind, n(row, "adjusted_debit_cents") - n(row, "adjusted_credit_cents"));
            let pri = natural(kind, n(row, "prior_debit_cents") - n(row, "prior_credit_cents"));
            for (t, v) in total.iter_mut().zip([base, adj, fin, pri]) { *t = t.saturating_add(v); }
            accts.push(json!({"account_id":row["id"],"code":row["code"],"name":row["name"],"unadjusted_cents":base,"adjustments_cents":adj,"final_cents":fin,"prior_cents":pri,"change_cents":fin.saturating_sub(pri)}));
        }
        let a = lines.entry(line).or_default();
        a.cur = a.cur.saturating_add(total[2]);
        a.pri = a.pri.saturating_add(total[3]);
        leadsheets.push(json!({"group_id":group.id,"code":group.code,"name":group.name,"kind":group.kind,"gifi_code":group.gifi_code,"statement_line":line.key(),"accounts":accts,
            "unadjusted_cents":total[0],"adjustments_cents":total[1],"final_cents":total[2],"prior_cents":total[3],"change_cents":total[2].saturating_sub(total[3])}));
    }
    let g = |l: Line| lines.get(&l).copied().unwrap_or_default();
    let sum = |ls: &[Line], cur: bool| ls.iter().map(|l| if cur { g(*l).cur } else { g(*l).pri }).fold(0i64, i64::saturating_add);
    let period = |cur: bool| {
        let revenue = sum(&[Line::Revenue], cur);
        let cos = sum(&[Line::CostOfSales], cur);
        let opex = sum(&[Line::OperatingExpense], cur);
        let tax = sum(&[Line::IncomeTax], cur);
        let gross = revenue - cos;
        let before_tax = gross - opex;
        let ni = before_tax - tax;
        let re_open = sum(&[Line::RetainedEarnings], cur);
        // Dividends are debit-natured equity; natural (credit) sign makes them negative.
        let dividends = -sum(&[Line::Dividends], cur);
        let re_close = re_open + ni - dividends;
        let ca = sum(&[Line::Cash, Line::CurrentAsset], cur);
        let assets = ca + sum(&[Line::LongTermAsset], cur);
        let cl = sum(&[Line::CurrentLiability], cur);
        let liabilities = cl + sum(&[Line::LongTermLiability], cur);
        let equity = sum(&[Line::ShareCapital, Line::OtherEquity], cur) + re_close;
        json!({
            "income_statement":{"revenue_cents":revenue,"cost_of_sales_cents":cos,"gross_profit_cents":gross,"operating_expenses_cents":opex,"income_before_taxes_cents":before_tax,"income_taxes_cents":tax,"net_income_cents":ni},
            "retained_earnings":{"opening_cents":re_open,"net_income_cents":ni,"dividends_cents":dividends,"closing_cents":re_close},
            "balance_sheet":{"cash_cents":sum(&[Line::Cash],cur),"other_current_assets_cents":sum(&[Line::CurrentAsset],cur),"current_assets_cents":ca,"long_term_assets_cents":sum(&[Line::LongTermAsset],cur),"total_assets_cents":assets,
                "current_liabilities_cents":cl,"long_term_liabilities_cents":sum(&[Line::LongTermLiability],cur),"total_liabilities_cents":liabilities,
                "share_capital_cents":sum(&[Line::ShareCapital],cur),"other_equity_cents":sum(&[Line::OtherEquity],cur),"retained_earnings_cents":re_close,"total_equity_cents":equity,
                "difference_cents":assets - liabilities - equity},
        })
    };
    let current = period(true);
    let prior = period(false);
    let has_prior = input.prior_period_end.is_some();
    let mut diagnostics: Vec<Value> = analysis["diagnostics"].as_array().cloned().unwrap_or_default();
    let cash_flow = if has_prior {
        let d = |l: Line| g(l).cur - g(l).pri;
        let ni = current["income_statement"]["net_income_cents"].as_i64().unwrap_or(0);
        let working_capital = -d(Line::CurrentAsset) + d(Line::CurrentLiability);
        let operating = ni + working_capital;
        let investing = -d(Line::LongTermAsset);
        let dividends = current["retained_earnings"]["dividends_cents"].as_i64().unwrap_or(0);
        let financing = d(Line::LongTermLiability) + d(Line::ShareCapital) + d(Line::OtherEquity) - dividends;
        let net = operating + investing + financing;
        let actual = d(Line::Cash);
        if net != actual {
            diagnostics.push(json!({"code":"cash_flow_unreconciled","message":format!("Derived cash flow differs from the change in cash by {} cents; review retained-earnings mapping and non-cash items.", net - actual),"blocking":true,"severity":"error"}));
        }
        json!({"method":"indirect","net_income_cents":ni,"change_in_non_cash_working_capital_cents":working_capital,"operating_cents":operating,"investing_cents":investing,"financing_cents":financing,"net_change_in_cash_cents":net,"cash_opening_cents":g(Line::Cash).pri,"cash_closing_cents":g(Line::Cash).cur,
            "limitation":"Derived from balance changes only; amortization, gains/losses and other non-cash items are not separated from investing activity."})
    } else {
        diagnostics.push(json!({"code":"cash_flow_requires_prior","message":"A cash flow statement needs prior-period comparatives.","blocking":false,"severity":"warning"}));
        Value::Null
    };
    if current["balance_sheet"]["difference_cents"].as_i64() != Some(0) {
        diagnostics.push(json!({"code":"statement_out_of_balance","message":"Draft balance sheet does not balance; check mapping.","blocking":true,"severity":"error"}));
    }
    // Uncorrected (proposed) entries: never in the adjusted basis.
    let kinds: BTreeMap<&str, &str> = input.accounts.iter().map(|a| (a.id.as_str(), a.kind.as_str())).collect();
    let mut proposed = Vec::new();
    let mut proposed_ni = 0i64;
    for entry in input.adjustments.iter().filter(|e| analysis::is_proposed(&e.kind)) {
        let mut ni = 0i64;
        let mut assets = 0i64;
        for l in &entry.lines {
            let net = l.debit_cents.saturating_sub(l.credit_cents);
            match kinds.get(l.account_id.as_str()).copied() {
                Some("revenue") => ni -= net,
                Some("expense") => ni -= net,
                Some("asset") => assets += net,
                _ => {}
            }
        }
        proposed_ni += ni;
        proposed.push(json!({"id":entry.id,"reference":entry.reference,"kind":entry.kind,"description":entry.description,"net_income_effect_cents":ni,"asset_effect_cents":assets}));
    }
    let supported = !diagnostics.iter().any(|d| d["blocking"] == true);
    let _ = &groups;
    json!({
        "format":FORMAT,"framework":"ASPE (draft presentation)","review_notice":REVIEW_NOTICE,"supported":supported,
        "engagement":{"name":input.name,"kind":input.kind,"period_start":input.period_start,"period_end":input.period_end,"prior_period_end":input.prior_period_end,"currency":input.currency},
        "current":current,"prior":if has_prior {prior} else {Value::Null},"cash_flow":cash_flow,
        "leadsheets":leadsheets,
        "uncorrected_misstatements":{"entries":proposed,"total_net_income_effect_cents":proposed_ni},
        "notes":notes(input),
        "diagnostics":diagnostics,
    })
}

/// Note skeletons. Wording is placeholder text pending CPA review.
pub fn notes(input: &EngagementInput) -> Value {
    let mut out = vec![
        json!({"number":1,"title":"Nature of operations","text":"[CPA REVIEW REQUIRED] Describe the entity's legal form, jurisdiction and principal activities."}),
        json!({"number":2,"title":"Significant accounting policies","text":"[CPA REVIEW REQUIRED] These draft financial statements are prepared using Canadian accounting standards for private enterprises. Describe revenue recognition, inventory, capital assets and amortization, income taxes and financial instruments policies as applicable."}),
    ];
    if input.kind == "compilation" {
        out[1] = json!({"number":2,"title":"Basis of accounting","text":"[CPA REVIEW REQUIRED] Describe the basis of accounting management used to prepare this compiled financial information; for a compilation, note disclosure is limited to the basis of accounting."});
        out.truncate(2);
        return Value::Array(out);
    }
    out.push(json!({"number":3,"title":"Capital assets","text":"[CPA REVIEW REQUIRED] Cost, accumulated amortization and net book value by class."}));
    out.push(json!({"number":4,"title":"Long-term debt","text":"[CPA REVIEW REQUIRED] Terms, security and five-year principal repayments."}));
    out.push(json!({"number":5,"title":"Share capital","text":"[CPA REVIEW REQUIRED] Authorized and issued shares."}));
    out.push(json!({"number":6,"title":"Financial instruments","text":"[CPA REVIEW REQUIRED] Significant risks arising from financial instruments."}));
    Value::Array(out)
}
