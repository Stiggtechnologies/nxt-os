//! Declared migration lanes. A lane with `vendor_format_observed: false` has
//! no pinned source file in this repository. The staged importer will not
//! invent that file's columns.

#[derive(Clone, Copy)]
pub struct Lane {
    pub id: &'static str,
    pub route: Option<&'static str>,
    pub module: &'static str,
    pub legacy_source: Option<&'static str>,
    pub status: &'static str,
    pub vendor_format_observed: bool,
    pub required_types: &'static [&'static str],
    pub money_types: &'static [&'static str],
    pub hash_types: &'static [&'static str],
    pub expected_export: &'static str,
    pub blockers: &'static [&'static str],
}

